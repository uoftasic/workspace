"""The KLayout libraries: one per PDK, one PCell per Magic generator."""

from ._kl import db
from .pcell import make_pcell

# The sky130A library's name, kept for code written against version 0.2.
LIBRARY_NAME = "sky130_magic"


class MagicLibrary(db.Library):
    """One PCell per Magic device or box-paint generator of one PDK.

    Not bound to a technology: a library bound to one would be invisible to
    layouts that have no technology set (the PDKs' own libraries skywater130
    and gf180mcu aren't bound either; IHP's SG13_dev is)."""

    def __init__(self, manifest, state):
        super().__init__()
        n_dev = sum(1 for s in manifest.devices if s.kind == "device")
        n_box = len(manifest.devices) - n_dev
        self.description = ("%s devices generated by Magic (%d PCells: %d devices, %d box-paint "
                            "generators)" % (manifest.pdk, len(manifest.devices), n_dev, n_box))
        self.layout().dbu = 0.001
        self.pcell_names = []
        for spec in manifest.devices:
            self.layout().register_pcell(spec.name, make_pcell(spec, state))
            self.pcell_names.append(spec.name)
        self.register(state.library_name)


Sky130MagicLibrary = MagicLibrary
